"""Count the lines that git blame still gives to the original author.

    python tools/original_author_lines.py            # substantive lines per file
    python tools/original_author_lines.py --all      # also blank lines and bare keywords
    python tools/original_author_lines.py --show F   # print those lines of file F

Blame runs with ``-w -M -C``, so lines that were only re-indented, moved or
copied into another file still count as his. By default it skips lines that
carry no authorship of their own, which a rewrite cannot avoid sharing with
any Python or C++ file: blank lines, lone brackets and quotes, and bare words
such as ``try:``, ``continue`` or ``return True``, plus ``async def run(bot):``,
the entry point every action must define.
"""
import argparse
import re
import subprocess
import sys
from pathlib import Path

AUTHOR = "patrykjanik"
ROOT = Path(__file__).resolve().parents[1]
BINARY = {".png", ".ico", ".jpg", ".gz", ".exe", ".dll", ".bin", ".zip", ".pyc"}
GENERATED = {"dashboard/package-lock.json"}
TRIVIAL = re.compile(
    r"""^(
        [\s(){}\[\];,:'"`]*                                     # punctuation only
      | (\"\"\"|''')                                            # docstring fence
      | (try|else|finally|except(\s+\w+)?|pass|break|continue|return(\s+(True|False|None|0|1|-1))?)\s*:?\s*;?
      | (import\s+[\w.]+|from\s+__future__\s+import\s+\w+)       # one bare import
      | \#\s*(include\s+<\w+(\.h)?>|pragma\s+once)              # C/C++ system header
      | (break|continue|return\s*\w*)\s*;                         # C/C++ jump
      | @\w+                                                    # bare decorator
      | async\s+def\s+run\(bot\):                                # the action entry point
    )$""", re.X)


def blamed_lines(path):
    out = subprocess.run(["git", "blame", "-w", "-M", "-C", "--line-porcelain", "--", path],
                         cwd=ROOT, capture_output=True, text=True, encoding="utf-8", errors="replace")
    author = None
    for line in out.stdout.splitlines():
        if line.startswith("author "):
            author = line[7:]
        elif line.startswith("\t"):
            yield author, line[1:]


def count(path, everything):
    return [text for author, text in blamed_lines(path)
            if author == AUTHOR and (everything or not TRIVIAL.match(text.strip()))]


def tracked_files():
    names = subprocess.run(["git", "ls-files"], cwd=ROOT, capture_output=True, text=True).stdout.split("\n")
    return [n for n in names if n and Path(n).suffix.lower() not in BINARY and (ROOT / n).is_file()]


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--all", action="store_true", help="count blank lines and bare keywords too")
    parser.add_argument("--show", metavar="FILE", help="print the counted lines of one file")
    args = parser.parse_args(argv)
    if args.show:
        for text in count(args.show, args.all):
            print(text)
        return 0
    rows = []
    for name in tracked_files():
        lines = count(name, args.all)
        if lines:
            rows.append((len(lines), name))
    rows.sort(reverse=True)
    for n, name in rows:
        note = "  (generated by npm)" if name in GENERATED else ""
        print(f"{n:6d}  {name}{note}")
    total = sum(n for n, _ in rows)
    print(f"{total:6d}  lines in {len(rows)} files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
